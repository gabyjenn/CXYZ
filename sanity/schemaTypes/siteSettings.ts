import { defineField, defineType } from 'sanity'

export const siteSettings = defineType({
  name: 'siteSettings',
  title: 'Footer & Settings',
  type: 'document',
  groups: [
    { name: 'footer', title: 'Footer', default: true },
    { name: 'question', title: 'Question module' },
    { name: 'site', title: 'Site' },
  ],
  fields: [
    defineField({ name: 'siteTitle', type: 'string', group: 'site', initialValue: 'Portfolio' }),
    defineField({
      name: 'theme',
      title: 'Color scheme',
      type: 'string',
      group: 'site',
      options: {
        list: [
          { title: 'White background, black text', value: 'light' },
          { title: 'Black background, white text', value: 'dark' },
        ],
        layout: 'radio',
      },
      initialValue: 'light',
    }),
    defineField({
      name: 'carouselInterval',
      title: 'Slideshow interval (seconds)',
      type: 'number',
      group: 'site',
      description: 'Seconds between slides. Empty = 30. Set 0 to turn the slideshow off.',
      initialValue: 30,
      validation: (r) => r.min(0).max(600),
    }),
    defineField({
      name: 'copyright',
      title: 'Copyright name',
      type: 'string',
      group: 'footer',
      description: 'Rendered as “© 2026 Name”',
    }),
    defineField({ name: 'email', type: 'string', group: 'footer', validation: (r) => r.email() }),
    defineField({ name: 'instagram', title: 'Instagram URL', type: 'url', group: 'footer' }),
    defineField({ name: 'substack', title: 'Substack subscribe URL', type: 'url', group: 'footer' }),
    defineField({
      name: 'portfolioPdf',
      title: 'Portfolio PDF (optional)',
      type: 'file',
      group: 'footer',
      options: { accept: 'application/pdf' },
    }),
    defineField({
      name: 'cvPdf',
      title: 'CV PDF (optional)',
      type: 'file',
      group: 'site',
      description: 'Adds a “Download CV” link under the CV list.',
      options: { accept: 'application/pdf' },
    }),
    defineField({
      name: 'questions',
      title: 'Questions',
      type: 'array',
      group: 'question',
      of: [{ type: 'string' }],
      description: 'Each visitor sees one of these, picked at random. Leave empty to hide the module.',
    }),
    defineField({
      name: 'question',
      title: 'Question (old single field)',
      type: 'string',
      group: 'question',
      description: 'Only used if the list above is empty. Move it into Questions and clear this.',
      hidden: ({ value }) => !value,
    }),
    defineField({
      name: 'questionThanks',
      title: 'Thank-you message',
      type: 'string',
      group: 'question',
      initialValue: 'Thank you.',
    }),
  ],
  preview: { prepare: () => ({ title: 'Footer & Settings' }) },
})
